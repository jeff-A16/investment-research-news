#!/usr/bin/env python3
"""Fetch approved public/authorized research APIs, with secret-safe audit logs."""
import argparse
import importlib.util
import json
import os
from pathlib import Path
import re
import ssl
import sys
import time
from urllib.error import HTTPError
from urllib.parse import urlencode
from urllib.request import Request,urlopen
import uuid
import xml.etree.ElementTree as ET
sys.dont_write_bytecode=True

PROVIDERS={
 'alphavantage':{'base':'https://www.alphavantage.co/query','env':'ALPHAVANTAGE_API_KEY','secret_param':'apikey'},
 'marketaux':{'base':'https://api.marketaux.com/v1/','env':'MARKETAUX_API_TOKEN','secret_param':'api_token'},
 'finnhub':{'base':'https://finnhub.io/api/v1/','env':'FINNHUB_API_KEY','secret_header':'X-Finnhub-Token'},
 'gdelt':{'base':'https://api.gdeltproject.org/api/v2/doc/doc','env':None},
 'nyfed_sofr':{'base':'https://markets.newyorkfed.org/api/rates/secured/sofr/last/1.json','env':None},
 'treasury_cash':{'base':'https://api.fiscaldata.treasury.gov/services/api/fiscal_service/v1/accounting/dts/operating_cash_balance','env':None},
 'eastmoney_research':{'base':'https://reportapi.eastmoney.com/','env':None},
 'wallstreetcn_rss':{'base':'https://dedicated.wallstreetcn.com/rss.xml','env':None,'format':'rss'},
 'fed_monetary_rss':{'base':'https://www.federalreserve.gov/feeds/press_monetary.xml','env':None,'format':'rss'},
 'fed_speeches_rss':{'base':'https://www.federalreserve.gov/feeds/speeches.xml','env':None,'format':'rss'},
 'danjuan_valuation':{'base':'https://danjuanfunds.com/djapi/index_eva/dj','env':None},
 'funddb_valuation':{'base':'https://ai2.jiucaishuo.com/api/index-valuation','env':None},
}
ENDPOINTS={'marketaux':{'news/all','news/sources'},'finnhub':{'news','company-news','quote','calendar/earnings'},'eastmoney_research':{'report/org','report/dg','report/jg','report/list'}}

def main():
 p=argparse.ArgumentParser(description=__doc__)
 p.add_argument('--provider',choices=PROVIDERS,required=True)
 p.add_argument('--run',required=True)
 p.add_argument('--source-ids',nargs='+',required=True)
 p.add_argument('--params-file',help='JSON parameters; never put secrets in this file')
 p.add_argument('--endpoint',default='')
 p.add_argument('--demo',action='store_true',help='Official Alpha Vantage demo only; not user registration')
 p.add_argument('--timeout',type=float,default=20)
 args=p.parse_args();cfg=PROVIDERS[args.provider]
 run=Path(args.run).resolve();skill=Path(__file__).resolve().parent.parent
 spec=importlib.util.spec_from_file_location('audit',skill/'scripts/run_logger.py')
 log=importlib.util.module_from_spec(spec);spec.loader.exec_module(log)
 params=json.loads(Path(args.params_file).read_text()) if args.params_file else {}
 if not isinstance(params,dict):raise ValueError('Parameters must be a JSON object')
 if any(re.search(r'(?i)(?:token|key|password|secret|authorization)',k) for k in params):
  raise ValueError('Pass API credentials using the named environment variable, not parameter files')
 if args.endpoint and args.endpoint not in ENDPOINTS.get(args.provider,set()):raise ValueError('Unsupported endpoint')
 if args.provider in ENDPOINTS and not args.endpoint:raise ValueError('--endpoint is required')
 if args.demo and args.provider!='alphavantage':raise ValueError('--demo is only for the official Alpha Vantage demo')
 if args.provider=='alphavantage':
  allowed={'TIME_SERIES_DAILY','NEWS_SENTIMENT','EARNINGS','INCOME_STATEMENT','TREASURY_YIELD','GLOBAL_QUOTE'}
  if params.get('function') not in allowed:raise ValueError('Choose a supported documented read-only function')
 if args.provider=='gdelt':
  params={'mode':'artlist','format':'json','maxrecords':'10','timespan':'24h',**params}
  if not params.get('query'):raise ValueError('GDELT requires query, e.g. gold domain:reuters.com')
 if args.provider=='treasury_cash':params={'sort':'-record_date','page[size]':'5',**params}
 if args.provider=='funddb_valuation':params={'category':'jx',**params}
 if args.provider=='eastmoney_research':
  if 'cb' in params:raise ValueError('JSONP callback is generated by the adapter')
  if args.endpoint!='report/org':
   params={'pageNo':1,'pageSize':50,'beginTime':'','endTime':'',**params}
   if not 1<=int(params['pageSize'])<=50:raise ValueError('pageSize must be 1..50')
  # Public front-end index.js uses these callback prefixes. Parse data, never eval JSONP.
  params['cb']=('showData' if args.endpoint=='report/org' else 'datatable')+str(int(uuid.uuid4().hex[:6],16)%10000000+1)
 key='demo' if args.demo else (os.environ.get(cfg['env']) if cfg['env'] else None)
 def event(kind,data):
  with log.locked(run):return log.append_unlocked(run,kind,data)
 if cfg['env'] and not key:
  event('gap',{'provider':args.provider,'source_ids':args.source_ids,'status':'credential_missing',
       'required_env':cfg['env'],'registration_status':'not verified; do not claim API access'})
  print(json.dumps({'status':'credential_missing','required_env':cfg['env'],'request_sent':False}));sys.exit(2)
 call_id='api-'+uuid.uuid4().hex[:12];started=time.monotonic()
 headers={'User-Agent':'FinancialResearchSkills/3.0','Accept':'application/json','Accept-Encoding':'identity'}
 actual={**params}
 if cfg.get('secret_param'):actual[cfg['secret_param']]=key
 if cfg.get('secret_header'):headers[cfg['secret_header']]=key
 base=cfg['base']+args.endpoint
 url=base+('?' if actual else '')+urlencode(actual)
 event('tool_start',{'call_id':call_id,'source_ids':args.source_ids,'tool':'financial_api.GET',
       'started_at':log.now(),'arguments':{'provider':args.provider,'url':base,'params':log.clean(actual),
       'headers':log.clean(headers),'timeout':args.timeout,'credential_mode':'official_demo' if args.demo else ('environment' if key else 'not_required')}})
 status=None;body=b'';error=None;response_headers={}
 try:
  try:response=urlopen(Request(url,headers=headers),timeout=args.timeout,context=ssl.create_default_context())
  except HTTPError as exc:response=exc
  with response:
   status=response.status
   response_headers={k:v for k,v in response.headers.items() if k.lower() in ('date','content-type','retry-after','x-ratelimit-remaining')}
   chunks=[]
   try:
    while True:
     chunk=response.read(65536)
     if not chunk:break
     chunks.append(chunk)
   finally:body=b''.join(chunks)
 except Exception as exc:error=type(exc).__name__+': '+str(exc)
 # Credential values are redacted even if an upstream error echoes them.
 text=body.decode('utf-8',errors='replace')
 if key and key!='demo':text=text.replace(key,'[REDACTED_API_CREDENTIAL]')
 if error and key:error=error.replace(key,'[REDACTED_API_CREDENTIAL]')
 payload=None
 json_text=text
 if args.provider=='eastmoney_research':
  match=re.fullmatch(re.escape(params['cb'])+r'\s*\((.*)\)\s*;?\s*',text,re.S)
  json_text=match.group(1) if match else text
 try:payload=json.loads(json_text)
 except json.JSONDecodeError:pass
 if cfg.get('format')=='rss':
  try:
   feed=ET.fromstring(text)
   if feed.tag=='rss':payload={'feed_title':feed.findtext('./channel/title'),'entries':[{'title':(i.findtext('title') or '').strip(),'original_url':i.findtext('link'),'feed_pub_date_raw':i.findtext('pubDate'),'description_html':i.findtext('description')} for i in feed.findall('./channel/item')]}
  except ET.ParseError:pass
 outcome='http_error' if status is None or status>=400 else 'ok'
 if error:outcome='transport_error'
 elif status is None or status>=400:outcome='rate_limited' if status==429 else ('authentication_failed' if status==401 else 'http_error')
 elif payload is None:outcome='non_json_response'
 elif isinstance(payload,dict) and any(k in payload for k in ('Error Message','Information','Note','error','errors')):outcome='provider_error_or_entitlement_limit'
 elif args.provider=='alphavantage':
  expect={'TIME_SERIES_DAILY':'Time Series (Daily)','NEWS_SENTIMENT':'feed','GLOBAL_QUOTE':'Global Quote','EARNINGS':'annualEarnings','INCOME_STATEMENT':'annualReports','TREASURY_YIELD':'data'}[params['function']]
  if not isinstance(payload,dict) or expect not in payload:outcome='unexpected_schema'
 elif args.provider=='marketaux' and (not isinstance(payload,dict) or 'data' not in payload):outcome='unexpected_schema'
 elif args.provider=='finnhub':
  if args.endpoint in ('news','company-news') and not isinstance(payload,list):outcome='unexpected_schema'
  elif args.endpoint=='quote' and (not isinstance(payload,dict) or 'c' not in payload):outcome='unexpected_schema'
  elif args.endpoint=='calendar/earnings' and (not isinstance(payload,dict) or 'earningsCalendar' not in payload):outcome='unexpected_schema'
 elif args.provider=='nyfed_sofr' and (not isinstance(payload,dict) or not payload.get('refRates')):outcome='unexpected_schema'
 elif args.provider=='treasury_cash' and (not isinstance(payload,dict) or not payload.get('data')):outcome='unexpected_schema'
 elif args.provider=='gdelt' and (not isinstance(payload,dict) or 'articles' not in payload):outcome='unexpected_schema'
 elif args.provider=='eastmoney_research' and not (isinstance(payload,list) or isinstance(payload,dict) and isinstance(payload.get('data'),list)):outcome='unexpected_schema'
 elif cfg.get('format')=='rss' and (not isinstance(payload,dict) or not isinstance(payload.get('entries'),list)):outcome='unexpected_schema'
 elif args.provider=='danjuan_valuation' and (not isinstance(payload,dict) or not isinstance(payload.get('data'),dict) or not isinstance(payload['data'].get('items'),list)):outcome='unexpected_schema'
 elif args.provider=='funddb_valuation' and (not isinstance(payload,dict) or not isinstance(payload.get('rows'),list) or not payload.get('new_update_time')):outcome='unexpected_schema'
 relative='artifacts/apis/'+call_id+'.json'
 saved={'provider':args.provider,'http_status':status,'outcome':outcome,'error':error,
        'headers':response_headers,'data':payload,'raw_visible_response':text,'credential_mode':'official_demo' if args.demo else ('environment' if key else 'not_required')}
 with log.locked(run):
  raw=log.canonical(saved)+b'\n';log.save_new(log.target(run,relative),raw)
  log.append_unlocked(run,'artifact_saved',{'path':relative,'sha256':log.digest(raw),'bytes':len(raw),
      'metadata':{'kind':'API response with credential redaction','provider':args.provider},'credential_review':'tokens redacted before write'})
 event('tool_end',{'call_id':call_id,'status':'success' if outcome=='ok' else 'error','ended_at':log.now(),
       'duration_ms':round((time.monotonic()-started)*1000),'truncated':False,'result_paths':[relative],
       'gaps':[] if outcome=='ok' else [outcome]})
 event('coverage',{'source_ids':args.source_ids,'provider':args.provider,'outcome':outcome,
        'credential_mode':saved['credential_mode'],'artifact':relative,
        'limitation':'API success is not proof that all named publishers, original full text, social platforms, or latest data are covered.'})
 count=None
 if isinstance(payload,list):count=len(payload)
 elif isinstance(payload,dict):
  record_key={'gdelt':'articles','nyfed_sofr':'refRates','treasury_cash':'data','marketaux':'data','eastmoney_research':'data','wallstreetcn_rss':'entries','funddb_valuation':'rows'}.get(args.provider)
  if cfg.get('format')=='rss':record_key='entries'
  if args.provider=='alphavantage':record_key={'TIME_SERIES_DAILY':'Time Series (Daily)','NEWS_SENTIMENT':'feed','GLOBAL_QUOTE':'Global Quote','EARNINGS':'annualEarnings','INCOME_STATEMENT':'annualReports','TREASURY_YIELD':'data'}[params['function']]
  value=payload.get(record_key) if record_key else None
  if args.provider=='danjuan_valuation':
   nested=payload.get('data')
   value=nested.get('items') if isinstance(nested,dict) else None
  if isinstance(value,(list,dict)):count=len(value)
 print(json.dumps({'provider':args.provider,'outcome':outcome,'http_status':status,
       'record_count':count,'artifact':relative,'credential_mode':saved['credential_mode']},ensure_ascii=False))
 if outcome!='ok':sys.exit(3)

if __name__=='__main__':
 try:main()
 except (OSError,ValueError,KeyError) as exc:
  print('API client error: '+str(exc),file=sys.stderr);sys.exit(1)
